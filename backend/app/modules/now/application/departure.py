#: The name this act is filed under in the command log. ADR-0030 keys the log
#: ``(command, idempotency key)``, so the name is half the key and is fixed here
#: rather than at the route: a second spelling of it would be a second namespace,
#: and a replay filed under the wrong one is a departure applied twice.
DEPARTURE_COMMAND = "departure"

#: Every way the aggregate says *not now*, and all of them answer with the
#: screen. Each is a state ADR-0070's rule was written for — the act no longer
#: applies, and what she needs is what is true now:
#:
#: - the quote fell between the tap and the apply (ADR-0033);
#: - she has already left, which is the naive retry of a departure whose
#:   response never arrived, and the reason the log's absence is survivable;
#: - the match started, so there is no departure to make;
#: - it was cancelled, and nobody leaves a match that is not happening;
#: - ADR-0046's lock closed on a converted court that is bought and full.
_REFUSALS = (
    DepartureOutcomeWorsened,
    SeatNotTaken,
    MatchAlreadyStarted,
    MatchAlreadySettled,
    DepartureLocked,
)


@dataclass(frozen=True)
class DepartureQuery:
    """Who is asking what leaving this match is worth."""

    player_id: UUID
    match_id: UUID


@dataclass(frozen=True)
class DepartCommand:
    """*Leave*, at the outcome she was looking at, under her own request key.

    ``quote`` is a **label and never an amount** (ADR-0033): an amount moves for
    reasons that have nothing to do with leaving, and refusing on those is
    noise.

    ``idempotency_key`` is generated by the client and is **not** the version
    ADR-0074 refused. A version would make the phone hold a rule about its own
    staleness; a key encodes no rule and states no belief about freshness. It
    answers one case a version could not — a phone that loses the answer to a
    departure it already made.
    """

    player_id: UUID
    match_id: UUID
    quote: Outcome
    idempotency_key: str


@dataclass(frozen=True)
class DepartureAnswer:
    """A write's answer: its own screen, Now's update, and what the tap did.

    ``applied`` is the outcome the departure was **made at**, and it is the one
    thing on this response that is a fact about the *command* rather than about
    the match. It is ``None`` exactly when nothing was applied, which is the
    only thing its absence can mean — and it is what stops *was I refused*
    being a rule on the phone. Deriving it from ``may_depart`` still being true
    is a rule (ADR-0053), and the acknowledgement ADR-0070 leaves to the client
    is a sentence it can only write if it knows.

    On a replay it comes back off the command log rather than off the aggregate,
    which is ADR-0030's *"a replayed key returns the first outcome"*: what she
    got the first time, not what leaving would be worth now.
    """

    screen: DepartureScreen
    update: NowUpdate
    applied: Outcome | None = None


class ReadDeparture:
    """What leaving is worth right now, and what it could still become."""

    def __init__(self, *, enrolled: EnrolledMatches, clock: Clock) -> None:
        self._enrolled = enrolled
        self._clock = clock

    async def execute(self, query: DepartureQuery) -> DepartureScreen:
        now = instant(self._clock.now())
        row = await _row(self._enrolled, query.player_id, query.match_id, now)
        return _screen(row, now=now, stamp=stamp_at(now))


class MakeDeparture:
    """Leave, and hand back both screens off the player's own tap."""

    def __init__(
        self,
        *,
        enrolled: EnrolledMatches,
        departures: Departures,
        log: CommandLog,
        uow: UnitOfWork,
        clock: Clock,
    ) -> None:
        self._enrolled = enrolled
        self._departures = departures
        self._log = log
        self._uow = uow
        self._clock = clock

    async def execute(self, command: DepartCommand) -> DepartureAnswer:
        now = instant(self._clock.now())

        # Asked before anything is loaded, because a replay must write nothing
        # at all — including the read that would find her seat already gone and
        # refuse for the wrong reason.
        remembered = await self._log.recall(
            command=DEPARTURE_COMMAND, key=command.idempotency_key, now=now
        )
        if remembered is not None:
            if remembered.player_id != command.player_id:
                raise IdempotencyKeyIsAnothers()
            return await self._answer(
                command, now=now, applied=Outcome(remembered.result)
            )

        # The membership read comes first even though the write repeats it: a
        # stranger gets a 404 and never reaches the aggregate, which is
        # authorisation rather than a refusal of the act (ADR-0074).
        await _row(self._enrolled, command.player_id, command.match_id, now)

        try:
            applied = await self._departures.depart(
                match_id=command.match_id,
                player_id=command.player_id,
                quote=command.quote,
                at=now,
            )
        except _REFUSALS:
            # Nothing applied, and the screen recomposed at this instant is the
            # correction that matters — *what is true now* rather than a
            # sentence about a rule.
            return await self._answer(command, now=now, applied=None)

        await self._log.remember(
            LoggedCommand(
                command=DEPARTURE_COMMAND,
                key=command.idempotency_key,
                player_id=command.player_id,
                # What she **got**, not what she asked for: equal or better
                # applies, so a forfeit quoted against a reversal goes through
                # and the forfeit is what a replay has to hand back.
                result=applied.value,
                recorded_at=now,
            )
        )
        await self._uow.commit()
        return await self._answer(command, now=now, applied=applied)

    async def _answer(
        self, command: DepartCommand, *, now: Instant, applied: Outcome | None
    ) -> DepartureAnswer:
        """All three parts of the response, off one read of what is now true.

        Read **after** the commit rather than composed from the aggregate the
        write held: the screen and the card have to describe the record as it
        stands, and a leaver's card carries facts — her departure's money form,
        her seat's counting — that only the full read assembles.
        """

        stamp = stamp_at(now)
        row = await _row(self._enrolled, command.player_id, command.match_id, now)
        return DepartureAnswer(
            screen=_screen(row, now=now, stamp=stamp),
            update=CardChanged(card=card_of(row, now=now, stamp=stamp)),
            applied=applied,
        )


async def _row(
    enrolled: EnrolledMatches, player_id: UUID, match_id: UUID, now: Instant
) -> Enrolment:
    """Her relationship to this match, or a 404 for somebody who has none.

    ADR-0074's hardest case is the one this keeps: **a leaver resolves**. A 404
    tells her the match never existed, which is the class of defect ADR-0030 was
    written against. The stranger is the only 404, and it is authorisation.
    """

    row = await enrolled.one(player_id=player_id, match_id=match_id, now=now)
    if row is None:
        raise MatchNotFound()
    return row


def _screen(row: Enrolment, *, now: Instant, stamp: Stamp) -> DepartureScreen:
    """The route's own answer, built off the card the strip would have drawn.

    ``card_of`` is the one place a card is composed, so the spine, the situation
    and ``may_depart`` here are the same expressions the strip's card carries —
    there is no second reading of the ladder and no second answer to *may this
    person leave*. What this adds is the outcome table, which is the whole
    reason the act needed a route and not a card: it is the thing a card
    demonstrably has no room for.
    """

    card: MatchCard = card_of(row, now=now, stamp=stamp)
    record = row.record
    return DepartureScreen(
        match_id=card.match_id,
        where=card.where,
        price=card.price,
        situation=card.situation,
        clock=card.clock,
        may_depart=card.may_depart,
        # The kernel's own function and never the table's searching row read
        # back out: the table is composed *from* this, and deriving it the other
        # way would be a second answer to the question the quote protects.
        quote=live_outcome(record, now),
        outcomes=outcome_table(record, now),
        counts=card.situation.facts.counts,
        commitment_deadline=commitment_deadline(record),
    )
