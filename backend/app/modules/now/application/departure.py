"""The two halves of ADR-0086's route: read the quote, then act on it.

**The route is the confirmation.** One primary button carrying the quote, no
third step, and she is not asked twice — a confirm dialog over a screen whose
entire job is to state the consequence asks the same question twice, and the
refuse-and-re-present rule already gives her the only correction that matters.

**A refusal is not a second shape** (ADR-0070). Every way this act can no longer
apply — the quote fell, the match started, it was cancelled, ADR-0046's lock
closed, she has already left — comes back as **what a success returns**: the
same screen, recomposed, saying what is true now. The player *sees* that she
cannot leave rather than being told it, and the client has one code path instead
of two. The only two things that answer differently are not about the act at all
— a stranger's 404, and a request key that is somebody else's.

**Now's update rides back in the same response** (ADR-0074). Recomposing on the
pop was refused there: every ask pays the full funnel, and paying it on a return
from a screen the server has just finished computing is a cost bought for
tidiness. The card and the screen are composed from **one** read at one instant,
so the two halves of the answer cannot disagree.

**The write is one transaction and the command log is inside it.** The
departure, its vacancy, the hold ladder's answer, both outbox rows and the log
row close together — a log that could disagree with the write it describes is
the one state that makes a replay dangerous rather than merely useless.
"""

