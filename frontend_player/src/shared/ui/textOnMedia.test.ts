/**
 * The one rule this system has for text over a **generated** fill, and the arithmetic that
 * makes it a rule rather than a hope.
 *
 * Every pair in `docs/design-system.md` 2.5 is a fixed pair — two hexes, one ratio. The
 * court is neither: its ground runs from the selected Sport's hue to a dark end, so the
 * ratio behind a white label depends on which Sport a player picked, and no fixed pair can
 * state it. #219 B6 closed that by **pinning the scrim**: at `color.courtScrim` the hue
 * is at most 7% of the ground, the dark end is a constant, and the light end is one of
 * **four** known composites — four ratios to compute rather than an unbounded set.
 *
 * **The competitive card's photo panel is the second such ground, and the harder one**
 * ([#309](https://github.com/Rakieta02/Rakieta/issues/309)). The court's ground is at least
 * *generated* — four hues, one gradient, one scrim. A player's photograph is generated by
 * nobody: it can be a white wall, a floodlit court at noon or a silhouette, and the set of
 * grounds behind a label on it is not merely large but **unknowable**. The same instrument
 * closes it, and closes it harder: pin the scrim, and an unknowable set collapses to its
 * **worst case**, which for white text is the brightest ground there can be — pure white.
 * One composite and one ratio, and every real photograph is better than it.
 *
 * This file is the computation, and the WCAG arithmetic under it is `contrast.testkit.ts`'s,
 * so the court's four rows, the poster's two and the panel's one are one formula. 2.5's rows
 * are **derived here and copied there**, exactly as the level bar's edges are derived in
 * `bandEdges.test.ts` rather than asserted, so unpinning either scrim or retuning a Sport hue
 * goes red instead of going unnoticed.
 *
 * A test and not a runtime check, for the reason `bandEdges.test.ts` gives: a `theme.ts`
 * that checked its own arithmetic would be the app refusing to launch over a drawing detail,
 * and a red build is where a human reconciles it.
 */

import { composite, contrast, parse, type Rgb } from '@/test-support/contrast';
import { POSTER_HUES, theme, type SportKey } from './theme';

/** WCAG 2.1 requires 4.5:1 for text below the large-text threshold. Nothing here is above it. */
const AA = 4.5;

/**
 * The court's ground at its **light end** — the worst case for a label on it.
 *
 * The ground is a 150° gradient from the Sport hue to `night`, under one `courtScrim` pass.
 * At the dark end that composite is `night` whatever the Sport; at the light end it is the
 * hue showing through the pinned alpha, which is the four values this file computes.
 */
function courtGround(sport: SportKey): Rgb {
  const scrim = parse(theme.color.courtScrim);
  return composite(scrim.rgb, scrim.alpha, parse(theme.sport[sport]).rgb);
}

const WHITE = parse(theme.color.surface).rgb;

/** Low to high in ratio, so the first row is the one every other row clears. */
const SPORTS = ['tennis', 'badminton', 'padel', 'squash'] as const satisfies readonly SportKey[];

describe('the court scrim', () => {
  it('is pinned, which is the whole reason the four ratios below are computable', () => {
    expect(parse(theme.color.courtScrim).alpha).toBe(0.93);
  });

  it('is the night colour rather than a black, exactly as the sheet scrim is', () => {
    expect(parse(theme.color.courtScrim).rgb).toEqual(parse(theme.color.night).rgb);
  });
});

describe('white on the court ground (2.5)', () => {
  /** The four rows in 2.5. Copied from here, never the other way round. */
  const PUBLISHED: Readonly<Record<SportKey, number>> = {
    tennis: 12.29,
    badminton: 12.8,
    padel: 12.87,
    squash: 13.03,
  };

  it.each(SPORTS)('clears AA on %s, by a margin the pin guarantees', (sport) => {
    expect(contrast(WHITE, courtGround(sport))).toBeGreaterThanOrEqual(AA);
  });

  it.each(SPORTS)('is the ratio 2.5 publishes for %s', (sport) => {
    expect(contrast(WHITE, courtGround(sport))).toBe(PUBLISHED[sport]);
  });

  /**
   * B6 asked for the side labels to be raised off white `.6` *to whatever clears 4.5*. Under
   * the pinned scrim they already do, so nothing is raised and the finding is pinned instead
   * — a value left alone on evidence is one the next reader will otherwise change back.
   */
  it('still clears AA at the .6 white the side labels are drawn in', () => {
    const SIDE_LABEL_ALPHA = 0.6;
    const worst = Math.min(
      ...SPORTS.map((sport) => {
        const ground = courtGround(sport);
        return contrast(composite(WHITE, SIDE_LABEL_ALPHA, ground), ground);
      }),
    );

    expect(worst).toBeGreaterThanOrEqual(AA);
    // Pinned as well as bounded: 2.5 prints this figure as the reason the value is left
    // alone, and a published number nothing derives is one of the two documents drifting.
    expect(worst).toBe(5.46);
  });
});

/**
 * The panel's ground, at the **worst photograph there can be**.
 *
 * White is the brightest sRGB colour, so it is the ground white text has the least of a ratio
 * against — the composite under a pinned scrim is monotone in what is under it. Every real
 * photograph is darker somewhere and never lighter anywhere, so the figure this returns is a
 * floor for all of them rather than a sample of one.
 */
const PHOTO_SCRIM = parse(theme.color.photoScrim);

/** The scrim over whatever is behind it — one function, because it is one pass either way. */
function panelGround(under: Rgb): Rgb {
  return composite(PHOTO_SCRIM.rgb, PHOTO_SCRIM.alpha, under);
}

function worstPhotograph(): Rgb {
  return panelGround(WHITE);
}

describe('the photo panel scrim (2.5)', () => {
  /** The one row in 2.5. Copied from here, never the other way round. */
  const PUBLISHED = 5.24;

  it('is pinned, which is the whole reason a ratio over a photograph is computable at all', () => {
    expect(PHOTO_SCRIM.alpha).toBe(0.7);
  });

  it('is the night colour rather than a black, exactly as the other two scrims are', () => {
    expect(PHOTO_SCRIM.rgb).toEqual(parse(theme.color.night).rgb);
  });

  it('clears AA over the worst photograph there can be, which is a white one', () => {
    expect(contrast(WHITE, worstPhotograph())).toBeGreaterThanOrEqual(AA);
  });

  it('is the ratio 2.5 publishes', () => {
    expect(contrast(WHITE, worstPhotograph())).toBe(PUBLISHED);
  });

  /**
   * The panel is drawn identically over the generated poster, so its thirty-two stops are
   * grounds this scrim also sits on. They are **better than the bound rather than rows of
   * their own** — which is why 2.5 gains one row here and not thirty-three.
   */
  it('is better over every poster stop than over that worst case', () => {
    for (const hue of POSTER_HUES) {
      for (const stop of [hue.light, hue.dark]) {
        expect(contrast(WHITE, panelGround(parse(stop).rgb))).toBeGreaterThanOrEqual(PUBLISHED);
      }
    }
  });

  /**
   * **The floor is derived, and the pin sits above it.**
   *
   * A white photograph stops clearing AA at `.65` — 4.51, a published figure with nothing
   * left in it. The pin is the next step that has room, which is the same judgement 2.5 makes
   * everywhere: a ratio one rounding away from failing is a ratio the next tuning of anything
   * takes under. Both halves are computed here, so lightening the scrim toward the floor goes
   * red on the second assertion rather than going unnoticed on neither.
   */
  it('sits above the floor the arithmetic finds, rather than on it', () => {
    const FLOOR = 0.65;
    const at = (alpha: number) => contrast(WHITE, composite(PHOTO_SCRIM.rgb, alpha, WHITE));

    expect(at(FLOOR)).toBeGreaterThanOrEqual(AA);
    expect(at(FLOOR - 0.01)).toBeLessThan(AA);
    expect(PHOTO_SCRIM.alpha).toBeGreaterThan(FLOOR);
  });
});

/**
 * **The ON COURT mark is the panel's third label, and its tightest pair**
 * ([#313](https://github.com/Rakieta02/Rakieta/issues/313)).
 *
 * The Level and the Sport are white, which is the best a foreground can do over this ground.
 * The mark is green because green is what the verdict is worth reading as, and green over a
 * dark scrim is where a palette runs out: this block is the arithmetic that picks which green,
 * rather than the eye picking the one that looks right.
 */
describe('the ON COURT mark over that scrim (2.5)', () => {
  /** The one row 2.5 gains. Copied from here, never the other way round. */
  const PUBLISHED = 4.55;

  it('clears AA in `mintSoft` over the worst photograph there can be', () => {
    expect(contrast(parse(theme.color.mintSoft).rgb, worstPhotograph())).toBeGreaterThanOrEqual(AA);
  });

  it('is the ratio 2.5 publishes', () => {
    expect(contrast(parse(theme.color.mintSoft).rgb, worstPhotograph())).toBe(PUBLISHED);
  });

  /**
   * **`mint` itself is not a foreground here, and that is measured rather than assumed.**
   *
   * It is Rule C's problem in the other direction: `mint` is a *mark* colour, and over a
   * ground this dark it is barely separated from it at all. The panel's scrim is what makes
   * the soft legible and the base illegible at the same time, which is why the mark takes the
   * one colour in the pair that is otherwise a background.
   */
  it('would be a line nobody sees in `mint`, which is why the soft is the foreground', () => {
    const asMint = contrast(parse(theme.color.mint).rgb, worstPhotograph());

    expect(asMint).toBeLessThan(AA);
    expect(asMint).toBe(1.29);
  });

  /**
   * The mark is drawn identically over the generated poster, exactly as the two white labels
   * are — so the poster's thirty-two stops clear the same bound by construction rather than
   * adding thirty-two rows to 2.5.
   */
  it('is better over every poster stop than over that worst case', () => {
    const mintSoft = parse(theme.color.mintSoft).rgb;
    for (const hue of POSTER_HUES) {
      for (const stop of [hue.light, hue.dark]) {
        expect(contrast(mintSoft, panelGround(parse(stop).rgb))).toBeGreaterThanOrEqual(PUBLISHED);
      }
    }
  });
});

describe('the textOnMedia shadow', () => {
  it('is drawn in a black that is dark enough to separate white from any ground', () => {
    expect(parse(theme.shadow.textOnMedia.textShadowColor).alpha).toBeGreaterThanOrEqual(0.6);
  });

  /**
   * A shadow WCAG cannot score. It is required on both label sets rather than one, because
   * the ratios above are the ground's *light end* and a label can sit anywhere on the ramp.
   */
  it('offsets and blurs, so it survives a label sitting on its own colour', () => {
    expect(theme.shadow.textOnMedia.textShadowRadius).toBeGreaterThan(0);
    expect(theme.shadow.textOnMedia.textShadowOffset.height).toBeGreaterThan(0);
  });
});
