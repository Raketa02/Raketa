/**
 * The **photo panel** — the photograph with the facts that outrank it printed on top
 * ([7.16](../../../docs/design-system.md#716-the-photo-panel),
 * [#309](https://github.com/Rakieta02/Rakieta/issues/309)).
 *
 * It replaced a bare 74 × 92 thumbnail on the competitive candidate card, and the replacement
 * is a statement about the product:
 *
 * > **In this product your rating is your face; the photograph is scenery.**
 *
 * So the **Level** is the biggest text on the panel, the **Sport** sits small and capitalised
 * under it, and the top of the panel carries the **ON COURT** mark
 * ([#313](https://github.com/Rakieta02/Rakieta/issues/313)) — which is why the content column is
 * anchored to the bottom rather than centred. The mark is what the space was left clear for,
 * and it arrived as a label rather than as the designs' shield: `OnCourtMark` holds that
 * arithmetic, and the short version is that the panel is 74pt wide and the words are 51,19 of
 * them.
 *
 * ## Two sizes, and the larger one **re-derives** rather than scaling
 *
 * The record sheet's header is the second composition to draw one
 * ([#384](https://github.com/Rakieta02/Rakieta/issues/384)), at `PHOTO_PANEL.record` — which is
 * why this component came below both features with `PlayerPhoto` and `OnCourtMark`, on the
 * same argument that moved the run of form and the Social tag row: `player_record` may not
 * import `features/play/`, because Play is what opens the sheet.
 *
 * Every number here is arithmetic against the panel's **own** width — the corner is a third of
 * it, and what the corner leaves at the mark's top edge is what the mark's cap is derived
 * from — so the second size is a second derivation and never a multiplier. Two things differ
 * with it and nothing else does: the box, and the Level's type role, which steps up to
 * `num.levelLarge` because a 22pt figure inside a 112pt panel stops being the biggest thing on
 * it. The pinned `photoScrim` and its worst-case 5,24:1 are unchanged at both, which is what
 * makes one contrast row cover both sizes rather than two.
 *
 * ## The mark sits at `space.md`, not `space.xs`, since it gained its tick
 *
 * The content layer is padded by `space.xs` and the mark used to sit at that edge. A drawn tick
 * before the words ([ADR-0169](../../../../docs/adr/0169-the-deck-lives-on-players-and-a-swipe-is-an-answer.md)
 * §7) does not fit there on a 74pt panel — the corner leaves 57,22 and the line wants 61,03 —
 * so the mark takes `space.xs` more of top margin, putting its edge at `space.md` (`MARK_TOP`,
 * 12pt down rather than 6), where the corner leaves 67,20 and both fit with the grid's smallest
 * step clear on each side. The Level and the Sport are anchored to the bottom and did not move;
 * `onCourtMarkFit.test.ts` re-derives the cap from this edge.
 *
 * ## Text over an arbitrary photograph, and the pin that makes it computable
 *
 * Every pair in [2.5](../../../docs/design-system.md#25-contrast--computed) is a
 * **fixed** pair — two hexes and one ratio. The court broke that once already: its ground is
 * drawn from a Sport hue, so #219 B6 **pinned `courtScrim`** and an unbounded set collapsed
 * to four known composites. A player's photograph is the same problem one turn worse: it is
 * generated by nobody, it can be a white wall or a floodlit court at noon, and the set of
 * grounds behind a label on it is not large but **unknowable**.
 *
 * The same instrument closes it. `theme.color.photoScrim` is pinned at **.70**, and an
 * unknowable set collapses to its **worst case** — for white text, the brightest ground there
 * can be, which is pure white. White over that composite is **5.24:1**, AA, and every real
 * photograph is darker somewhere and never lighter anywhere. One ratio, derived in
 * [`textOnMedia.test.ts`](./textOnMedia.test.ts) rather than asserted, so
 * unpinning the scrim goes red instead of going unnoticed.
 *
 * **The panel is drawn identically over the generated poster**, which is why 2.5 gains one row
 * and not thirty-three: the poster's thirty-two stops are all darker than white, so they clear
 * the same bound by construction, and the test proves it rather than sampling it.
 *
 * All three labels carry `textOnMedia`, on 2.5's rule for every label over a ground nobody
 * chose: the ratio is the ground's brightest case and a label can sit anywhere on a
 * photograph. The mark is the tightest of the three at **4,55:1** — it is the one that is
 * green rather than white, and green is where a palette runs out over a dark ground.
 *
 * ## It announces nothing, and the sport in particular
 *
 * §20.1 merges an actionless element into the nearest action above it, which here is the card
 * body — so the three labels are plain `Text` and **not** a hidden subtree, exactly as
 * `CardHead` and `FactRow` are. `PlayerPhoto` hides *itself* because it carries a name of
 * its own; labels that carry none merge by having nothing to merge.
 *
 * The **Level reaches the spoken name already**, as the first figure of `levelRow` — it is
 * printed twice and said once, which is the whole of §10 holding while the drawing repeats. The
 * **Sport does not reach it at all on a card, and that is deliberate**: it is the search's own
 * sport, identical on every row, and the screen's eyebrow has already said it. Twenty rows each
 * opening with *Tennis* is the noise §20.3's fixed order exists to prevent. On the record sheet
 * it does reach the spoken name, because there it is the sport the panel resolved to and
 * nothing else on the sheet has said it.
 *
 * The **mark reaches it, and it is the exception that proves the Sport's rule**: it is true of
 * one player and not of the next, so it is a fact rather than a constant, and §20.3 gives it a
 * clause. `candidateFacts` composes both from one answer, which is why this component is handed
 * a boolean rather than a verdict — the rule is `domain/onCourtMark`'s and reading it twice is
 * two chances to fold *flagged* and *never checked* apart.
 */

import { StyleSheet, Text, View } from 'react-native';

import { formatLevel } from '@/shared/formatting/ratingFormat';

import { OnCourtMark } from './OnCourtMark';
import { PHOTO_PANEL, PlayerPhoto, playerPhotoRadius, type PhotoPanelSize } from './PlayerPhoto';
import { theme } from './theme';

/**
 * Where the mark's top edge sits, down from the panel's own: `space.md`, the content padding
 * and as much again — see the module note. Exported for the fit test, which derives the cap
 * against it.
 */
export const MARK_TOP = theme.space.md;

export interface PhotoPanelProps {
  /** Whose face this is. The poster's whole input, and the reason it survives a reinstall. */
  readonly playerId: string;
  /** Omitted with `photo_id` when they have no photo, and on a link that has expired. */
  readonly photoUrl?: string;
  /**
   * **What they published**, and the sport it is published in — the two facts printed over the
   * photograph, or **nothing at all**.
   *
   * `level` is `player_card.level` and not `level_fit.theirMu`: they are the same number today
   * and they are two fields, and a panel printing the term's μ would go blank the day
   * `LEVEL_FIT` stands down. The panel is the composition's identity rather than part of its
   * argument, so it is drawn whatever fired.
   *
   * `sportName` is the **surface's**, never the subject's: on a card it is the search's own
   * sport, identical on every row; on the record sheet it is the sport the server resolved the
   * skill panel to, which is the one thing on that panel a reader has been told nowhere else.
   *
   * **Absent together, and only on the record sheet.** Somebody rated in nothing has no
   * resolved sport and therefore no Level to print — and *no Level* is the poster with nothing
   * over it, never a nought. A candidate always holds a rating in the sport that returned them,
   * so no card ever omits this.
   */
  readonly rating?: {
    readonly level: number;
    readonly sportName: string;
  };
  /**
   * Whether the photograph wears the ON COURT mark — one answer, read once by the surface, so
   * that the drawing and the spoken name cannot disagree about it.
   *
   * A boolean and **not** the verdict, which is the whole of what keeps *checked and flagged*
   * and *nobody looked* indistinguishable: a component handed the code could branch on it a
   * second way, and the second way is the one that publishes a moderation outcome about
   * somebody who is not looking at this screen.
   */
  readonly onCourt: boolean;
  /**
   * Which composition this panel is in — a card's, or the record sheet's header.
   *
   * Defaults to `card`, which is the shape that existed first and the one every candidate card
   * draws. It is the panel's **whole** geometry and not a scale factor: see the module note.
   */
  readonly size?: PhotoPanelSize;
}

export function PhotoPanel({
  playerId,
  photoUrl,
  rating,
  onCourt,
  size = 'card',
}: PhotoPanelProps) {
  const panel = PHOTO_PANEL[size];

  return (
    <View style={[s.panel, { ...panel, borderRadius: playerPhotoRadius(panel.width) }]}>
      <PlayerPhoto playerId={playerId} photoUrl={photoUrl} box={{ kind: 'panel', size }} />

      {/* One flat pass, and not a gradient. A gradient would put the label somewhere on a ramp
          and hand back the unbounded set the pin exists to close: the worst case would depend
          on where the text happened to sit, which is not a thing a test can hold. */}
      <View style={[StyleSheet.absoluteFill, s.scrim]} />

      <View style={[StyleSheet.absoluteFill, s.content]}>
        {onCourt ? (
          <View style={s.mark}>
            <OnCourtMark on={size} />
          </View>
        ) : null}

        {/* Its own block, so the two facts stay at the bottom whether or not the mark is
            above them: `space-between` over an absent first child would carry them up. */}
        {rating === undefined ? null : (
          <View style={s.labels}>
            <Text style={[s.level, LEVEL_ROLE[size]]}>{formatLevel(rating.level)}</Text>
            <Text style={s.sport} numberOfLines={1}>
              {rating.sportName}
            </Text>
          </View>
        )}
      </View>
    </View>
  );
}

/**
 * The Level's type role, per size — the one thing besides the box that the second size moves.
 *
 * *In this product your rating is your face*, so the Level is the biggest text on the panel at
 * whichever size the panel is. 22pt reads as huge inside 74 and merely large inside 112, which
 * would quietly demote the one fact the composition exists to lead with.
 */
const LEVEL_ROLE = StyleSheet.create({
  card: theme.num.xl,
  record: theme.num.levelLarge,
});

const s = StyleSheet.create({
  // The photograph, the scrim and the labels share one corner: the clip is the panel's, so
  // whichever of the three is inside it takes the same radius. One owner, as `PlayerPhoto`
  // already insisted for the ratio itself. The box itself is applied at the call site above,
  // because it is the one thing here that depends on which size is being drawn.
  panel: { overflow: 'hidden' },
  scrim: { backgroundColor: theme.color.photoScrim },
  // The mark at the top and the two facts at the bottom, which is the layout #309 left room
  // for. One padding for all three, and one more step for the mark: its top edge is what its
  // cap is derived against, so `MARK_TOP` is read in `onCourtMarkFit.test.ts` rather than
  // guessed at.
  content: { padding: theme.space.xs },
  // `space.xs` more under the `space.xs` padding, so the mark's top edge is `MARK_TOP`.
  mark: { marginTop: MARK_TOP - theme.space.xs },
  labels: { flex: 1, justifyContent: 'flex-end' },
  level: {
    ...theme.tabular,
    color: theme.color.surface,
    ...theme.shadow.textOnMedia,
  },
  /**
   * `tag` uppercased rather than `eyebrow`, and the reason is arithmetic.
   *
   * An eyebrow is the right ROLE — it labels a region somebody is reading — but its 1,43pt
   * tracking is sized for a heading across a screen. Inside a 74pt panel it costs *Badminton*
   * about thirteen points, which is more room than the panel has: the widest of the four sport
   * names would ellipsize on every card in the app. `tag` is the same 9,5 / 700 with no
   * tracking, and the capitals are the caller's here rather than the role's.
   */
  sport: {
    ...theme.type.tag,
    color: theme.color.surface,
    textTransform: 'uppercase',
    ...theme.shadow.textOnMedia,
  },
});
